// Treatment protocols: a library of point prescriptions, each tagged TCM or Classical.
//
// Each protocol is one prescription. Conditions are plain text (searchable); there is no separate
// condition list. Classical protocols may carry a school (Five Element, Nan Jing, ...).
//
// Point entries: [code, method, role]. Method is one or more of:
//   +  tonify    -  reduce    =  even    M  moxa    B  bleed / prick    T  test / leave in place
// A protocol either has `pts` (one prescription) or `sets` (a choice of related prescriptions,
// e.g. one per channel); `add` lists optional additions.
//
// The content is written for study, in our own words. `refs` point to suggested further reading,
// not page citations. `review: true` marks entries whose details vary between teachers or need
// checking against the source texts.
