function cfProtocol(el) {
  const orgs = EL_INFO[el].organs;
  const role = (o, what) => `${what} of the ${OFFICIALS[o]}`;
  return {
    id: 'cf-' + el.toLowerCase(), tradition: 'classical', school: 'five', group: 'Five Element procedures',
    name: `${el} Causative Factor treatment`, zh: EL_INFO[el].zh,
    conditions: CF_CONDITIONS[el],
    desc: `In Five Element constitutional acupuncture the practitioner looks for the one element whose imbalance underlies the patient's problems: the Causative Factor (CF), or guardian element. Treatment is aimed at that element's officials rather than at the presenting complaint. A ${el} constitution is recognised mainly by colour (${CF_COLOUR[el]}), sound (${CF_SOUND[el]}), odour (${CF_ODOUR[el]}) and emotion (${CF_EMOTION[el]}).`,
    principle: `Support the officials of ${el}${orgs.length > 2 ? ' (inner and outer Fire)' : ''}: usually start with the Source points, then the tonification points; use the horary points in the element's own season (${EL_INFO[el].season.toLowerCase()}) and two-hour period.`,
    sets: [
      { name: 'Source (Yuan) points', pts: orgs.map((o) => [catPt('yuan', o), '+', role(o, 'Source point')]) },
      { name: 'Tonification points', pts: orgs.map((o) => [catPt('tonify', o), '+', role(o, `Tonification (${mother(el)}) point`)]) },
      { name: 'Horary points (in season)', pts: orgs.map((o) => [catPt('horary', o), '+', role(o, `Horary (${el}) point`)]) },
    ],
    notes: `Clear blocks first (Aggressive Energy, Possession, Husband–Wife, Entry–Exit) before working on the CF. Treatments are typically few needles, tonified briefly, often preceded by moxa where allowed.${orgs.length > 2 ? ' Fire has four officials: Heart and Small Intestine (inner Fire), Heart Protector and Three Heater (outer Fire). Practitioners usually decide which pair is primary.' : ''}`,
    refs: ['worsley', 'hicks', 'franglen'],
  };
}

function entryExitProtocol() {
  const sets = FLOW.map((from, i) => {
    const to = FLOW[(i + 1) % 12];
    const ex = CATEGORIES.exit.pts[i], en = CATEGORIES.entry.pts[(i + 1) % 12];
    return { name: `${from} → ${to}`, pts: [[ex, '+', `Exit point of the ${MN[from].name}`], [en, '+', `Entry point of the ${MN[to].name}`]] };
  });
  return {
    id: 'entry-exit', tradition: 'classical', school: 'five', group: 'Five Element procedures',
    name: 'Entry–Exit blocks', zh: '',
    conditions: ['treatment not holding', 'symptoms along a channel'],
    desc: 'Qi circulates through the twelve officials in the horary order (LU → LI → ST → … → LR → LU). A block between two consecutive channels shows on the pulses as excess in one and deficiency in the next, and sometimes as symptoms along the channel. It is cleared by tonifying the exit point of the full channel and then the entry point of the empty one.',
    principle: 'Pick the pair whose pulses show the block; tonify the exit point, then the entry point, on both sides.',
    sets,
    notes: 'Some of the most common blocks are Liver → Lung (LR14 → LU1), Spleen → Heart (SP21 → HT1) and Small Intestine → Bladder (SI19 → BL1). Lineages differ on the entry or exit point of a few channels; check against your own teaching.',
    review: true,
    refs: ['hicks', 'worsley'],
  };
}

function nanjing69Protocol() {
  const sets = [];
  for (const mer of FLOW) {
    const m = MN[mer], el = m.el;
    const mo = mother(el), sn = son(el);
    const moCh = channelOf(mo, m.yy), snCh = channelOf(sn, m.yy);
    sets.push({ name: `${mer} deficient`, pts: [[elementPoint(mer, mo), '+', `${mo} (mother) point on its own channel`], [elementPoint(moCh, mo), '+', `${mo} point of the mother channel (${moCh})`]] });
    sets.push({ name: `${mer} excess`, pts: [[elementPoint(mer, sn), '-', `${sn} (son) point on its own channel`], [elementPoint(snCh, sn), '-', `${sn} point of the son channel (${snCh})`]] });
  }
  return {
    id: 'nanjing-69', tradition: 'classical', school: 'nanjing', group: 'Nan Jing & meridian therapy',
    name: 'Mother–son treatment (Nan Jing 69)', zh: '虚则补其母，实则泻其子',
    conditions: ['channel deficiency', 'channel excess'],
    desc: '“In deficiency tonify the mother, in excess drain the son.” For a deficient channel, tonify the point of the mother phase on that channel, together with the mother phase point on the mother channel. For an excess channel, drain the son phase point on the channel and on the son channel.',
    principle: 'Diagnose by comparing the pulse positions; choose the channel, then whether it is deficient or excess.',
    sets,
    notes: 'For Earth, Fire channels are paired using the Heart and Small Intestine. Japanese meridian therapy uses a modified form of this rule for its four basic patterns.',
    refs: ['nanjing', 'matsumoto'],
  };
}

function yuanLuoProtocol() {
  const sets = FLOW.map((mer) => {
    const p = MN[mer].partner;
    return { name: `${mer} first, then ${p}`, pts: [[catPt('yuan', mer), '=', `Yuan-Source (host) point of the ${MN[mer].name}`], [catPt('luo', p), '=', `Luo-Connecting (guest) point of the ${MN[p].name}`]] };
  });
  return {
    id: 'yuan-luo', tradition: 'classical', school: 'combo', group: 'Named combinations',
    name: 'Host–guest (Yuan–Luo) combination', zh: '原络配穴',
    conditions: ['paired channel disorders'],
    desc: 'When a disorder starts in one channel and spreads to its interior–exterior partner, needle the Yuan-Source point of the channel affected first (the host) with the Luo-Connecting point of its partner (the guest).',
    principle: 'Choose the channel affected first; combine its Yuan point with the partner channel\'s Luo point.',
    sets,
    refs: ['cam', 'deadman'],
  };
}

